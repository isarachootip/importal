import type { CaseDetailDto } from "@/components/packaging/case-detail-types";
import type { getCaseDetail } from "@/lib/services/case-service";

type LoadedCaseDetail = NonNullable<Awaited<ReturnType<typeof getCaseDetail>>>;

function isoOrNull(dt: Date | null | undefined): string | null {
  return dt ? dt.toISOString() : null;
}

export function serializeCaseDetail(detail: LoadedCaseDetail): CaseDetailDto {
  const c = detail.importCase;
  const p = c.packaging;

  return {
    id: c.id,
    caseCode: c.caseCode,
    productTitle: c.productTitle,
    brandId: c.brandId,
    brandName: c.brand.name,
    owner: { id: c.owner.id, thaiName: c.owner.thaiName, nickname: c.owner.nickname },
    subclassName: c.subclass?.nameTh ?? null,
    vendorName: c.vendor?.name ?? null,
    currentStage: c.currentStage,
    sourcingStatus: c.sourcingStatus,
    poStatus: c.poStatus,
    productionStatus: c.productionStatus,
    logisticStatus: c.logisticStatus,
    isNewPhoto: c.isNewPhoto,
    requiresTisi: c.requiresTisi,
    requiresFda: c.requiresFda,
    isTileImport: c.isTileImport,
    isNewBrandOrLogo: c.isNewBrandOrLogo,
    sourcingPlanEnd: isoOrNull(c.sourcingPlanEnd),
    sourcingActualEnd: isoOrNull(c.sourcingActualEnd),
    poPlanEnd: isoOrNull(c.poPlanEnd),
    poActualEnd: isoOrNull(c.poActualEnd),
    prodPlanEnd: isoOrNull(c.prodPlanEnd),
    prodActualEnd: isoOrNull(c.prodActualEnd),
    logisticPlanEnd: isoOrNull(c.logisticPlanEnd),
    logisticActualEnd: isoOrNull(c.logisticActualEnd),
    poNumber: c.poNumber,
    poTotalAmount: c.poTotalAmount !== null ? Number(c.poTotalAmount) : null,
    poCurrency: c.poCurrency,
    incoterm: c.incoterm,
    shippingMode: c.shippingMode,
    forwarderName: c.forwarderName,
    blOrAwbNumber: c.blOrAwbNumber,
    containerNumber: c.containerNumber,
    etd: isoOrNull(c.etd),
    eta: isoOrNull(c.eta),
    whIssueNote: c.whIssueNote,
    closedAt: isoOrNull(c.closedAt),
    quotations: c.quotations.map((q) => ({
      id: q.id,
      vendorId: q.vendorId,
      vendorName: q.vendorName,
      unitPrice: Number(q.unitPrice),
      currency: q.currency,
      moq: q.moq,
      leadTimeDays: q.leadTimeDays,
      incoterm: q.incoterm,
      notes: q.notes,
      isSelected: q.isSelected,
      createdAt: q.createdAt.toISOString(),
    })),
    documents: c.documents.map((d) => ({
      id: d.id,
      stage: d.stage,
      docType: d.docType,
      fileName: d.fileName,
      mimeType: d.mimeType,
      sizeBytes: d.sizeBytes,
      createdAt: d.createdAt.toISOString(),
      uploadedBy: d.uploadedBy,
    })),
    leadTimeAlerts: detail.leadTimeAlerts,
    packaging: p
      ? {
          id: p.id,
          piNumber: p.piNumber,
          piDate: p.piDate.toISOString(),
          skuCount: p.skuCount,
          caseConfigId: p.caseConfigId,
          caseNumber: p.caseConfig.caseNumber,
          caseConfigName: p.caseConfig.name,
          currentStep: p.currentStep,
          timelineStatus: p.timelineStatus,
          isMinorChange: p.isMinorChange,
          preQcRejectCount: p.preQcRejectCount,
          packagingTypeIds: p.packagingTypes.map((pt) => pt.packagingTypeId),
          packagingTypeNames: p.packagingTypes.map((pt) => pt.packagingType.nameTh),
          scheduleSteps: p.scheduleSteps.map((s) => ({
            id: s.id,
            stepKey: s.stepKey,
            plannedDays: s.plannedDays,
            plannedStart: s.plannedStart.toISOString(),
            plannedEnd: s.plannedEnd.toISOString(),
            actualStart: isoOrNull(s.actualStart),
            actualEnd: isoOrNull(s.actualEnd),
            isBuffer: s.isBuffer,
          })),
          piFiles: p.piFiles.map((f) => ({
            id: f.id,
            slot: f.slot,
            version: f.version,
            fileName: f.fileName,
            mimeType: f.mimeType,
            sizeBytes: f.sizeBytes,
            createdAt: f.createdAt.toISOString(),
            uploadedBy: f.uploadedBy,
          })),
          checklistAnswers: p.checklistAnswers.map((a) => ({
            checklistItemId: a.checklistItemId,
            checked: a.checked,
            note: a.note,
          })),
          preQcReviews: p.preQcReviews.map((r) => ({
            id: r.id,
            round: r.round,
            decision: r.decision,
            failedCodes: r.failedCodes,
            note: r.note,
            createdAt: r.createdAt.toISOString(),
            reviewer: r.reviewer,
          })),
          artworks: p.artworks.map((a) => ({
            id: a.id,
            stageKind: a.stageKind,
            version: a.version,
            fileName: a.fileName,
            mimeType: a.mimeType,
            sizeBytes: a.sizeBytes,
            createdAt: a.createdAt.toISOString(),
            uploadedBy: a.uploadedBy,
          })),
          approvals: p.approvals.map((a) => ({
            id: a.id,
            stepKey: a.stepKey,
            round: a.round,
            stepOrder: a.stepOrder,
            role: a.role,
            decision: a.decision,
            reason: a.reason,
            actedAt: isoOrNull(a.actedAt),
            actedBy: a.actedBy,
          })),
          comments: p.comments.map((cm) => ({
            id: cm.id,
            artworkVersionId: cm.artworkVersionId,
            authorRole: cm.authorRole,
            body: cm.body,
            pinNumber: cm.pinNumber,
            pinX: cm.pinX,
            pinY: cm.pinY,
            pageNumber: cm.pageNumber,
            createdAt: cm.createdAt.toISOString(),
            author: cm.author,
          })),
        }
      : null,
    auditEvents: c.auditEvents.map((e) => ({
      id: e.id,
      actorRole: e.actorRole,
      stage: e.stage,
      stepKey: e.stepKey,
      action: e.action,
      reason: e.reason,
      createdAt: e.createdAt.toISOString(),
      actor: e.actor,
    })),
  };
}
